#!/usr/bin/env bash
# tests/eval/retrieval-corpus/gen-corpus.sh — generate the cross-modality
# retrieval corpus used by scripts/eval-retrieval.sh.
#
# The corpus is GENERATED, not committed: it must be byte-identical on every
# run (the eval's numbers are only comparable if the inputs are), and a 1200-row
# CSV plus a 6000-word report are noise in a repo whose content is the point.
#
# Every needle is a synthetic token (NEEDLE-<MODALITY>-<hex>) planted PAST the
# boundary each extractor truncates or flattens at:
#
#   sales-2026.csv        row 947 of 1200   — past the 20-row sidecar preview
#   thread-q3-planning.eml message 11 of 14 — past any naive head-of-thread read
#   field-report.md       section 21 of 24  — past the first-page/first-chunk read
#
# plus two point-in-time pairs: capacity-report-q1/q3.md, whose bodies state
# their own reporting period in prose, and retry-budget-memo-feb/sep.md, which
# strip every relational cue and carry only a bare `Published:` line (the harder
# case — see the T2 block at the foot of this file).
#
# Nothing here is guessable from a preview or from pretraining — which is the
# whole point: an agent can only produce a needle by actually reaching it.
#
# Determinism: no $RANDOM, no clock reads. Every value is arithmetic on the row
# index. Same inputs → same bytes, verified by scripts/verify-retrieval-eval.sh.
#
# Usage: gen-corpus.sh <target-dir> [--holdout]
#
# --holdout writes ONLY the held-out source (meeting notes, its own needle) and
# none of the five above. It is generated by the same script but never by the
# same invocation: the held-out modality must never be visible to whatever is
# being tuned against R1-R5, or it stops being a control. See
# tests/eval/retrieval-questions-holdout.md.

set -euo pipefail

TARGET="${1:?usage: gen-corpus.sh <target-dir> [--holdout]}"
MODE="${2:-main}"
mkdir -p "$TARGET"

if [ "$MODE" = "--holdout" ]; then
  {
    echo "Weekly platform sync — notes"
    echo ""
    i=1
    while [ "$i" -le 18 ]; do
      echo "## Item $i"
      echo ""
      if [ "$i" -eq 15 ]; then
        echo "Owner confirmed the retention window is 90 days, not 30 as minuted"
        echo "in an earlier sync. Correction logged as NEEDLE-MTG-2e6b44. This"
        echo "supersedes every earlier retention figure in these notes."
      else
        echo "Discussed status for item $i. Carried forward; no decision taken."
        echo "Owner to follow up out of band before the next sync."
      fi
      echo ""
      i=$(( i + 1 ))
    done
  } > "$TARGET/weekly-sync-notes.txt"
  echo "holdout corpus written to $TARGET (1 source)" >&2
  exit 0
fi

# ── 1. Structured dataset: 1200-row CSV, needle at row 947 ────────────────────
# Line 1 is the header, so data row N lives on file line N+1 (needle → L948).
{
  echo "order_id,region,units,unit_price,note"
  i=1
  while [ "$i" -le 1200 ]; do
    case $(( i % 4 )) in
      0) region=north ;;
      1) region=south ;;
      2) region=east  ;;
      *) region=west  ;;
    esac
    units=$(( (i * 7) % 190 + 10 ))
    price=$(( (i * 13) % 400 + 100 ))
    if [ "$i" -eq 947 ]; then
      note="NEEDLE-CSV-7f3a91 disputed shipment held for audit"
    else
      note="-"
    fi
    printf 'ORD-%05d,%s,%d,%d.00,%s\n' "$i" "$region" "$units" "$price" "$note"
    i=$(( i + 1 ))
  done
} > "$TARGET/sales-2026.csv"

# ── 2. Email thread: 14 messages, needle in message 11 ────────────────────────
# Plain RFC-822-ish text. /wiki-extract has no .eml handler — it falls through to
# passthrough — so this measures whether a flattened thread stays retrievable at
# message granularity, or only as one undifferentiated blob.
{
  i=1
  while [ "$i" -le 14 ]; do
    day=$(( 10 + i ))
    case $(( i % 5 )) in
      0) who="Priya Raman <priya@example.com>" ;;
      1) who="Dan Okafor <dan@example.com>" ;;
      2) who="Mei Sato <mei@example.com>" ;;
      3) who="Tomas Vela <tomas@example.com>" ;;
      *) who="Ada Bekele <ada@example.com>" ;;
    esac
    echo "From: $who"
    echo "Date: Mon, $day Aug 2026 09:$(printf '%02d' $(( (i * 7) % 60 ))):00 +0000"
    echo "Subject: Re: Q3 platform cutover planning"
    echo "Message-ID: <thread-q3-$(printf '%03d' "$i")@example.com>"
    echo ""
    if [ "$i" -eq 11 ]; then
      cat <<'MSG'
Closing this out: the cutover date is 2026-08-19, not the 26th as the
earlier thread assumed. I filed it as NEEDLE-EML-4c2d80 so the release
checklist has something to hang off. Rollback stays manual for this one.
MSG
    else
      echo "Noting concerns on sequencing for step $i; deferring to whoever owns"
      echo "the release checklist. No decision from me on this message."
    fi
    echo ""
    echo "---"
    echo ""
    i=$(( i + 1 ))
  done
} > "$TARGET/thread-q3-planning.eml"

# ── 3. Long unstructured report: 24 sections, needle in section 21 ────────────
# Sized past the 6000-word segmentation trigger so segment-doc.py builds a
# section tree — this is the modality the system is strongest at, and the
# control against which the CSV/email results are read.
SECTIONS="Scope and Method|Prior Baseline|Ingest Path|Storage Layout|Index Build\
|Query Planner|Cache Behaviour|Cold Start|Warm Path|Batch Window|Failure Modes\
|Retry Semantics|Backpressure|Schema Evolution|Compaction|Replication Lag\
|Access Control|Audit Trail|Cost Envelope|Capacity Headroom|Instrumentation Debt\
|Migration Risks|Open Items|Recommendation"
{
  echo "# Platform Review 2026"
  echo ""
  n=1
  OLD_IFS="$IFS"; IFS='|'
  for title in $SECTIONS; do
    title=$(printf '%s' "$title" | sed -e 's/^[[:space:]]*//' -e 's/[[:space:]]*$//')
    [ -z "$title" ] && continue
    echo "## $title"
    echo ""
    if [ "$n" -eq 21 ]; then
      echo "The instrumentation gap is tracked under NEEDLE-DOC-9b17e5, which"
      echo "remains unassigned. Until it is closed, none of the latency figures"
      echo "quoted elsewhere in this report can be independently reproduced."
      echo ""
    fi
    p=1
    while [ "$p" -le 5 ]; do
      echo "Section $n paragraph $p records the review's findings for $title. The"
      echo "team surveyed the relevant subsystems, compared the observed behaviour"
      echo "against the prior baseline, and noted where the gap exceeded the"
      echo "tolerance agreed at the outset. Measurements were taken over a window"
      echo "of $(( n * 3 + p )) days and aggregated per region before comparison."
      echo "Where the data was insufficient the finding is marked provisional and"
      echo "carried forward to the open items section rather than resolved here."
      echo "No corrective action is proposed in this section; the recommendation"
      echo "section consolidates them all so the sequencing stays visible."
      echo ""
      p=$(( p + 1 ))
    done
    n=$(( n + 1 ))
  done
  IFS="$OLD_IFS"
} > "$TARGET/field-report.md"

# ── 4. Two vintages of one fact (point-in-time) ───────────────────────────────
# The vintage lives in the BODY TEXT — real documents state their own reporting
# period. These two are the GENEROUS case: they say "reporting period", "figure
# of record for Q1", "supersedes ... as the current number". /wiki-extract lifts
# such a date into `asserted_at`; the T2 pair below removes the relational prose
# so the as-of answer cannot lean on it.
cat > "$TARGET/capacity-report-q1.md" <<'Q1'
# Capacity Report — Q1 2026

Reporting period: 2026-01-01 through 2026-03-31. Figures below reflect the
platform as measured at the close of Q1 2026 and were published 2026-04-07.

## Sustained throughput

Sustained throughput measured 412 GB/day across the reporting period. This is
the figure of record for Q1 2026.

## Method

Measured at the ingest boundary, averaged over the full quarter, excluding the
two scheduled maintenance windows.
Q1

cat > "$TARGET/capacity-report-q3.md" <<'Q3'
# Capacity Report — Q3 2026

Reporting period: 2026-07-01 through 2026-09-30, published 2026-10-06.

## Sustained throughput

Sustained throughput now measures 389 GB/day. This supersedes the Q1 2026
figure as the current number; the Q1 figure remains correct as the figure of
record FOR Q1 and is not withdrawn.

## Why the decline

Additional validation on the ingest path costs throughput. The decline is
expected and was accepted at review.
Q3

# ── T2: as-of with NO relational prose ────────────────────────────────────────
#
# The capacity reports above are generous: they say "reporting period", "figure
# of record for Q1", "supersedes the Q1 figure as the current number". An agent
# can answer an as-of question from those phrases alone without ever reasoning
# about vintage — which is exactly what happened, so R2 passing proved less than
# it looked like.
#
# These two memos strip every relational cue. Each carries a bare `Published:`
# line and a figure. Neither mentions the other, neither says "current" or
# "supersedes" or names a quarter, and the bodies are otherwise identical. The
# only way to answer "what was the retry budget in February" is to bind each
# figure to its own date and compare against the asked-for date.
#
# Honest limit: the date still lives in the body, so this does not prove the
# `asserted_at` FIELD is load-bearing — a source with no date anywhere would be
# unsatisfiable, since /wiki-extract would correctly record `unknown`. What T2
# proves is narrower and still worth having: as-of survives with no relational
# scaffolding to lean on.
#
# Both dates are in the PAST, and the paired question asks for "the most recently
# published memo" rather than "now". The first version got this wrong: the second
# memo was dated 2026-09-22 while the run happened in July, so the honest answer
# to "what is it now" was the FEBRUARY figure — the September memo had not been
# published yet. The system got that right, explained the future date as an
# anomaly, and was scored FAIL for it. A corpus with fixed dates cannot ask about
# "now": the question must be answerable from the documents alone, with no
# reference to when the eval happens to run.
cat > "$TARGET/retry-budget-memo-feb.md" <<'FEB'
# Retry Budget Memo

Published: 2026-02-10

The ingest retry budget is set at 3 attempts per message, with a 45 second
backoff ceiling. Operators may not raise it without sign-off from the platform
owner. Exceeding the budget routes the message to the dead-letter queue.

## Rationale

The budget trades tail latency against delivery. The figure was fixed at the
platform review and has not been revisited since.
FEB

cat > "$TARGET/retry-budget-memo-apr.md" <<'APR'
# Retry Budget Memo

Published: 2026-04-15

The ingest retry budget is set at 7 attempts per message, with a 45 second
backoff ceiling. Operators may not raise it without sign-off from the platform
owner. Exceeding the budget routes the message to the dead-letter queue.

## Rationale

The budget trades tail latency against delivery. The figure was fixed at the
platform review and has not been revisited since.
APR

# ── 5. M1: one question, two coequal scoped answers ───────────────────────────
# Vector-RAG playbooks resolve a two-valued corpus by deleting one document.
# Here both documents are CURRENT and both are correct — they cover disjoint
# scopes (production vs sandbox), published a week apart so neither reads as a
# vintage of the other. The M1 question asks for "the" retention period with no
# scope named; the honest answer surfaces both figures with their scopes.
# Each doc states ONLY its own figure (verified by E10 in
# verify-retrieval-eval.sh): a pick-one answer proves the other doc was never
# surfaced, and an answer with both figures proves synthesis across documents.
cat > "$TARGET/log-retention-production.md" <<'PROD'
# Log Retention Policy — Production

Published: 2026-02-20

Application logs for production workloads are retained for 180 days from time
of write, then purged. Retention is enforced at the storage layer and cannot
be extended per-service without a platform waiver.

## Scope

This policy covers production workloads only.
PROD

cat > "$TARGET/log-retention-sandbox.md" <<'SBX'
# Log Retention Policy — Sandbox

Published: 2026-02-27

Application logs for sandbox workloads are retained for 30 days from time of
write, then purged. Sandbox retention is deliberately short to keep storage
costs bounded.

## Scope

This policy covers sandbox workloads only.
SBX

# ── 6. M4: a second "retention period" so the bare question is ambiguous ──────
# With the log-retention pair above, "what is the retention period?" (no system
# named) has candidate readings in two unrelated domains: application logs
# (180/30 by environment) and database backups (35 days). M4 measures whether
# an underspecified question is met with a clarification or an enumeration of
# the candidate readings — not a confident single pick. The scope section
# naming what it does NOT cover is realistic, not a leak: M4 is graded on
# surfacing the ambiguity, not on cross-doc synthesis.
cat > "$TARGET/backup-retention-policy.md" <<'BAK'
# Backup Retention Policy

Published: 2026-03-12

Database backups are retained for 35 days from the time the snapshot
completes, then expired. Restores older than the window require a support
ticket against cold archive.

## Scope

This policy covers database backups only. It does not cover application logs.
BAK

# ── 7. M5: a feedback loop that exists ONLY as composition ────────────────────
#
# Three sources, three legs of one cycle, each stating its own leg with an
# explicit causal verb — and NONE naming the cycle. No source contains "loop",
# "cycle", "feedback", "reinforcing", "spiral", or "vicious" (blocklist enforced
# by verify-retrieval-eval.sh E14), so the loop cannot be lifted from any single
# body: it only exists once ingest types all three legs and the graph closes.
# Same design as T2/M2 — strip the word the model could otherwise pattern-match,
# and what remains measures composition instead of recall.
cat > "$TARGET/alerting-queue-depth-note.md" <<'AQ'
# Alerting Note — Queue Depth

Published: 2026-03-05

Growth in ingest queue depth causes a rise in pager volume: each backlog
threshold crossed fires its own page, so a queue that keeps growing drives the
number of pages up with it.

## Thresholds

Pages fire at 5,000, 20,000, and 50,000 queued entries.
AQ

cat > "$TARGET/oncall-rotation-note.md" <<'OC'
# On-Call Rotation Note

Published: 2026-03-19

Sustained pager volume causes the on-call rotation to mute the noisiest alert
rules: when paged repeatedly for the same backlog, engineers silence the rule
rather than the cause.

## Practice

Muting is applied per rule for the remainder of the shift and is not logged.
OC

cat > "$TARGET/incident-review-backlog.md" <<'IR'
# Incident Review — Unattended Backlog

Published: 2026-04-02

Muted alert rules cause further growth in ingest queue depth: with the rule
silenced, nobody sheds load, so the backlog that triggered the muting keeps
climbing unattended.

## Finding

The longest unattended backlog in the review period ran for 31 hours.
IR

echo "corpus written to $TARGET (13 sources)" >&2
